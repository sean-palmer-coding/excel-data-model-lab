"""Build independently decodable workbooks used for desktop Excel smoke tests."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from pbixray import PBIXRay

from excelmodel import WorkbookModel


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"
OUTPUT = ROOT / "compatibility-suite" / "generated"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    small_template = DATA / "null_data_id.xlsx"
    supplier_template = DATA / "supplier-quality.xlsx"

    with PBIXRay(small_template) as source:
        small = source.get_table("TheTable")[["A", "N", "C", "S", "K"]]
    small = small.iloc[40:80].reset_index(drop=True)
    small.loc[0, "S"] = "Generated by Excel Model Lab"
    small_output = OUTPUT / "small-complete.xlsx"
    (
        WorkbookModel.from_template(small_template)
        .replace_table("TheTable", small)
        .add_measure("TheTable", "Generated Total K", "SUM('TheTable'[K])")
        .save(small_output)
    )

    with PBIXRay(supplier_template) as source:
        plant = source.get_table("Plant").iloc[:10].reset_index(drop=True)
        defect_type = source.get_table("Defect Type").iloc[:2].reset_index(drop=True)
    supplier_output = OUTPUT / "supplier-multi-table.xlsx"
    (
        WorkbookModel.from_template(supplier_template)
        .replace_tables({"Plant": plant, "Defect Type": defect_type})
        .add_measure("Metrics", "Generated Defect Quantity", "SUM('Metrics'[Defect Qty])")
        .save(supplier_output)
    )

    manifest = {
        "release": "0.3.1rc1",
        "verification": "Generated and independently decoded with PBIXRay",
        "desktop_excel_checkpoint": "pending calculation and save/reopen checks",
        "workbooks": [
            {
                "file": small_output.name,
                "sha256": digest(small_output),
                "expected": {"TheTable_rows": 40, "new_measure": "Generated Total K"},
            },
            {
                "file": supplier_output.name,
                "sha256": digest(supplier_output),
                "expected": {
                    "Plant_rows": 10,
                    "Defect Type_rows": 2,
                    "new_measure": "Generated Defect Quantity",
                },
            },
        ],
    }
    (OUTPUT / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
